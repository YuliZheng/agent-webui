// === background tasks (subagents / workflows / background shells) ===========
// Backend observes Task/Agent/Workflow tool_use blocks and Bash
// run_in_background launches on the CLI wire, plus their completion
// (<task-notification> user turns). Pushed as `background-tasks` on the
