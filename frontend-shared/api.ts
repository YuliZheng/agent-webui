// === interaction control plane (M2) =========================================
// Backend pushes `interaction-added` when claude fires a control_request that
// needs user input (permission to use a tool, AskUserQuestion).
// Frontend replies with `interaction-respond` (RPC).
// Backend pushes `interaction-removed` when the pending item leaves the map
// for any reason (answered, cancelled, process died, race with peer tab).
//
// AskUserQuestion piggybacks on `can_use_tool` — `toolName === "AskUserQuestion"`
// and the questions live in `input.questions`. Frontend switches UI by toolName.

export type InteractionToolInput = Record<string, unknown>;

export interface InteractionAdded {
  type: "interaction-added";
  sessionId: string;
  requestId: string;
  // CLI's control_request.request.subtype. Always "can_use_tool" in M2;
  // future subtypes (elicitation, hook_callback) error back as unsupported.
  subtype: string;
  // Set when subtype === "can_use_tool". The model wants to call this tool.
  toolName?: string;
  // The tool's input as Claude generated it. For AskUserQuestion, contains
  // `input.questions: [{ question, header, options: [{label, description}], multiSelect }]`.
  input?: InteractionToolInput;
  // The id of the assistant-generated tool_use block this can_use_tool refers
  // to. Lets the FE attach the permission card to its matching tool_use row in
  // the timeline (so it scrolls with the conversation instead of stacking in a
  // fixed bottom strip). Absent for non-can_use_tool subtypes.
  toolUseId?: string;
  // ISO timestamp when backend received the control_request.
  receivedAt: string;
}

export interface InteractionRemoved {
  type: "interaction-removed";
  sessionId: string;
  requestId: string;
  reason: "answered" | "cancelled" | "process_died" | "superseded";
}

// Response from the frontend to a pending interaction. Discriminated by `kind`.
//   allow         — generic tool permission: let claude run it. updatedInput
//                   optional, overrides the input claude proposed.
//   deny          — generic tool permission: refuse with a message the model
//                   will see as the tool_result.
//   ask-answers   — answers to an AskUserQuestion. Backend folds them into
//                   `updatedInput.answers = {question: text}` and responds
//                   with `behavior: allow`. The native AskUserQuestion tool
//                   reads `answers` and produces a normal (no-is_error)
//                   tool_result identical to TUI output.
export type InteractionAnswer =
  | { kind: "allow"; updatedInput?: InteractionToolInput }
  | { kind: "deny"; message: string }
  | {
      kind: "ask-answers";
      // One entry per question in input.questions, in the same order.
      answers: Array<{
        // The label of the option the user picked, or null when they typed Other.
        selectedLabel: string | null;
        // Free-text "Other" — present when the user clicked Other and typed a value.
        otherText?: string;
      }>;
    };

export interface InteractionRespondRequest {
  type: "interaction-respond";
  sessionId: string;
  requestId: string;
  answer: InteractionAnswer;
}

