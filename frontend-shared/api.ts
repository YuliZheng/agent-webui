export interface SessionListItem {
  id: string;
  cwd: string;
  mtime: string;
  size: number;
  // Which agent backend owns this session. Absent ⇒ "claude" (back-compat:
  // every pre-existing session and wire message defaults to claude).
  agent?: "claude" | "codex";
  // True when this session was spawned by the call-claude / call-codex peer
  // bridge skills (a headless Claude↔Codex peer-review worker), detected from
  // the fixed signature in its first user turn. Tooling artifact, not a real
  // conversation — the sidebar hides these by default. Absent/false otherwise.
  peer?: boolean;
  // True when Codex reports thread_source:"subagent" (or the equivalent
  // source.subagent metadata). This is distinct from an ordinary fork:
  // both may have parentSessionId, but only subagent worker threads are hidden
  // from the normal sidebar by default.
  subagent?: boolean;
  title?: string | null;
  // Where the title came from. "auto" = generated by the auto-titler,
  // "manual" = the user typed it in the rename UI. The frontend renders a
  // tiny marker for "manual" so the user can tell at a glance which rows
  // they curated themselves vs. which were named by the model.
  titleSource?: "auto" | "manual" | null;
  // One-glyph emoji picked by the auto-titler alongside the title. Used as
  // the row's avatar character. Manual-source rows usually don't have one
  // unless they retained an earlier auto-emoji; SessionRow falls back to
  // the title's first letter when this is empty.
  titleEmoji?: string | null;
  parentSessionId?: string | null;
  // "running" | "exited" | "failed" if a claude process is alive (or recently
  // alive) for this session; null/undefined when the backend has no record.
  // Populated from the in-memory processRegistry, so it reflects only this
  // server's children (CLI sessions outside this server show as null).
  status?: "running" | "exited" | "failed" | null;
  // One-line snippet of the most recent meaningful message in the session's
  // jsonl (last assistant text, or last user prompt for brand-new sessions).
  // Whitespace-collapsed and truncated to 80 chars + "…" if longer.
  preview?: string | null;
  // Role that produced `preview`; lets the sidebar distinguish a pending user
  // prompt from an assistant reply without guessing from the text itself.
  previewRole?: "user" | "assistant" | null;
  // ISO timestamp of the record `preview` was extracted from. Frontends should
  // prefer this over `mtime` for the row's right-side time, since file mtime
  // can be touched by sidechain writes that don't represent user-visible
  // activity. Falls back to file mtime if the record had no timestamp field.
  lastTurnAt?: string | null;
  // ISO timestamp of the most recent "boundary event" — i.e. a turn just
  // started (user message arrived) or just ended (claude reached end_turn).
  // Mid-turn assistant chunks and tool_use/tool_result writes do NOT update
  // this. Sidebar sort uses this field so two simultaneously-streaming
  // sessions don't keep swapping positions on every assistant chunk.
  // Initialized from file mtime on backend boot; overwritten by Date.now()
  // on every subsequent transition.
  lastBoundaryAt?: string | null;
  // ISO timestamp of the server-synced "read up to here" watermark — the
  // session's lastTurnAt at the moment it was last opened on ANY device.
  // A session is unread iff lastTurnAt > readAt. Lets a freshly-loaded
  // device clear badges that were already read elsewhere (offline catch-up).
  // Absent ⇒ never read on any device.
  readAt?: string | null;
  // Server-authoritative unread assistant-turn count. Local storage is only a
  // cold-start cache; list hydration replaces it with this global value.
  unreadCount?: number;
}

